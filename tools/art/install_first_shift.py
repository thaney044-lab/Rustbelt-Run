"""Validate and install local Blender renders into the project's sprite library."""
from pathlib import Path
from PIL import Image
import hashlib,json,shutil,sys
root=Path(__file__).resolve().parents[2]
out=root/'assets/art/first_shift';out.mkdir(parents=True,exist_ok=True)
metadata={};sources={}
for directory in map(Path,sys.argv[1:]):
 for key,value in json.loads((directory/'sprites.json').read_text()).items():
  source=directory/value['file'];image=Image.open(source)
  assert image.mode=='RGBA' and image.getbbox(),source
  assert image.size==tuple(v*3 for v in value['world_size']),source
  assert max(image.size)<=2048,source
  assert image.getpixel((0,0))[3]==0,source
  shutil.copyfile(source,out/source.name)
  metadata[key]=value;sources[key]={'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'dimensions':list(image.size),'alpha_bounds':list(image.getbbox())}
lines=['extends RefCounted','## Locally rendered asset anchors. Generated by tools/art/install_first_shift.py.','const DATA := {']
for key,v in metadata.items():
 lines.append('\t"%s": [preload("res://assets/art/first_shift/%s"), Vector2(%s, %s), Vector2(%s, %s)],' % (key,v['file'],*v['world_size'],*v['anchor']))
lines+=['}', '''
static func sprite(canvas: CanvasItem, name: String, at: Vector2, scale_value := 1.0, tint := Color.WHITE) -> void:
	var entry: Array = DATA[name]
	canvas.draw_texture_rect(entry[0], Rect2(at-entry[2]*scale_value,entry[1]*scale_value),false,tint)

static func strip(canvas: CanvasItem, name: String, left: float, top: float, width: float, tint := Color.WHITE) -> void:
	# End caps retain their proportions. The web repeats without stretching bolts/grating.
	var entry: Array = DATA[name]
	var cap := minf(30.0,width*0.28)
	var y: float = top-entry[2].y
	var height: float = entry[1].y
	var texture: Texture2D = entry[0]
	canvas.draw_texture_rect_region(texture,Rect2(left,y,cap,height),Rect2(0,0,cap*3,height*3),tint)
	canvas.draw_texture_rect_region(texture,Rect2(left+width-cap,y,cap,height),Rect2((entry[1].x-cap)*3,0,cap*3,height*3),tint)
	var x := left+cap
	while x < left+width-cap-0.01:
		var section_width := minf(32,left+width-cap-x)
		canvas.draw_texture_rect_region(texture,Rect2(x,y,section_width,height),Rect2(64*3,0,section_width*3,height*3),tint)
		x += section_width
''']
lines.append('\nstatic func column(canvas: CanvasItem, at: Vector2, height: float, width := 18.0, tint := Color.WHITE) -> void:\n\tvar entry: Array = DATA.support\n\tvar stretch := Vector2(width/20.0,height/147.5)\n\tcanvas.draw_texture_rect(entry[0],Rect2(at-entry[2]*stretch,entry[1]*stretch),false,tint)\n\nstatic var soft_texture: Texture2D\nstatic func glow(canvas: CanvasItem, at: Vector2, dimensions: Vector2, tint: Color) -> void:\n\tif not soft_texture:\n\t\tvar gradient := Gradient.new()\n\t\tgradient.set_color(0,Color.WHITE)\n\t\tgradient.set_color(1,Color(1,1,1,0))\n\t\tgradient.add_point(0.32,Color(1,1,1,0.35))\n\t\tvar texture := GradientTexture2D.new()\n\t\ttexture.gradient = gradient\n\t\ttexture.fill = GradientTexture2D.FILL_RADIAL\n\t\ttexture.fill_from = Vector2(0.5,0.5)\n\t\ttexture.fill_to = Vector2(1,0.5)\n\t\ttexture.width = 96\n\t\ttexture.height = 96\n\t\tsoft_texture = texture\n\tcanvas.draw_texture_rect(soft_texture,Rect2(at-dimensions/2,dimensions),false,tint)\n')
(root/'scripts/rendered_art.gd').write_text('\n'.join(lines)+'\n')
(out/'provenance.json').write_text(json.dumps({'workflow':'Original procedural geometry, local Blender Cycles; no image generation or external providers','source':'tools/art/render_first_shift.py','renderer':'Blender 4.3.2 / Cycles CPU / 48 samples / AgX','pixels_per_world_unit':3,'scope':'First Shift only','sprites':metadata,'validation':sources},indent=2)+'\n')
print('Installed',len(metadata),'RGBA sprites,',sum((out/v['file']).stat().st_size for v in metadata.values()),'bytes')
